#!/usr/bin/env python3
"""Generate 6502/65C02 coverage sources (oracle-filtered), like gen_ppc.py.

usage: gen_6502.py VASM6502_OLDSTYLE outdir
"""
import os, subprocess, sys, tempfile
from concurrent.futures import ThreadPoolExecutor

VASM, OUT = sys.argv[1], sys.argv[2]
MN = """adc and asl bit brk cmp cpx cpy dec eor inc jmp jsr lda ldx ldy lsr ora rol ror sbc sta stx sty stz trb
tsb bcc bcs beq bmi bne bpl bvc bvs bra blt bge clc cld cli clv dex dey inx iny nop pha php pla plp rti rts sec
sed sei tax tay tsx txa txs tya phx phy plx ply stp wai""".split()
OPS = ["", "a", "#$12", "#<ab", "#>ab", "#'A'", "#-1", "zp", "ab", "<ab", ">zp", "!zp", "|zp", "zp,x", "zp,y",
       "ab,x", "ab,y", "(zp),y", "(zp,x)", "(zp)", "(ab)", "(ab,x)", "$00", "0", "later", "later,x", "*",
       "*+2", "*-126", "*+129", "*+130", "*-128", "#1"]
cands = []
BR = "bcc bcs beq bmi bne bpl bvc bvs bra blt bge".split()
for m in MN:
    for o in OPS:
        if m in BR and not o.startswith("*"):
            continue    # absolute branch targets depend on the position
        cands.append(" %s %s" % (m, o) if o else " " + m)
for n in range(8):
    for m in ["rmb", "smb"]:
        cands.append(" %s%d zp" % (m, n)); cands.append(" %s %d,zp" % (m, n))
    for m in ["bbr", "bbs"]:
        cands.append(" %s%d zp,*" % (m, n)); cands.append(" %s %d,zp,*+3" % (m, n))
PRO = "zp = $12\nab = $1234\n"
EPI = "later = $56\n"

def ok(job):
    line, opt = job
    with tempfile.TemporaryDirectory() as d:
        open(os.path.join(d, "t.s"), "w").write(PRO + line + "\n" + EPI)
        p = subprocess.run([VASM, "-quiet", "-Fbin"] + opt + ["-o", os.path.join(d, "o"), "t.s"],
                           cwd=d, capture_output=True)
        return p.returncode == 0 and not p.stderr.strip()

os.makedirs(OUT, exist_ok=True)
for name, opt in [("m6502_insn0", []), ("m6502_wdc0", ["-wdc02"])]:
    with ThreadPoolExecutor(16) as ex:
        res = list(ex.map(ok, [(c, opt) for c in cands]))
    good = [c for c, r in zip(cands, res) if r]
    with open(os.path.join(OUT, name + ".s"), "w") as f:
        f.write("; gfasm-args: -Fbin %s\n; gfasm-cpu: 6502 oldstyle\n; generated by tests/gen/gen_6502.py (oracle-filtered)\n" % " ".join(opt))
        f.write(PRO + "; --\n")
        for c in good:
            f.write(c + "\n")
        f.write(EPI)
    print(name, len(good), "of", len(cands))
