def gen_basic(name, args, eas):
    c = []
    for mn in two:
        for m in sized(mn, ["", "b", "w", "l"]):
            for s in eas:
                for d in eas:
                    c.append("\t%s\t%s,%s" % (m, s, d))
    write(name + "_two", args, c)
    c = []
    for mn in one:
        for m in sized(mn, ["", "b", "w", "l"]):
            for s in eas:
                c.append("\t%s\t%s" % (m, s))
    write(name + "_one", args, c)

def gen_imm(name, args):
    c = []
    for mn in ["move", "add", "sub", "cmp", "and", "or", "eor", "movea", "adda", "suba", "cmpa"]:
        for m in sized(mn, ["b", "w", "l"]):
            for i in IMM:
                for d in ["d3", "a3", "(a3)", "-(sp)", "$1234.w", "4(a4)"]:
                    c.append("\t%s\t%s,%s" % (m, i, d))
    for mn in ["asl", "asr", "lsl", "lsr", "rol", "ror", "roxl", "roxr"]:
        for m in sized(mn, ["b", "w", "l"]):
            for i in ["#1", "#2", "#8", "d4"]:
                c.append("\t%s\t%s,d2" % (m, i))
    for mn in ["btst", "bchg", "bclr", "bset"]:
        for m in sized(mn, ["", "b", "l"]):
            for s in ["#0", "#7", "#31", "d1"]:
                for d in ["d2", "(a1)", "4(a2)", "$12.w", "#$12", "8(pc)", "(a3)+"]:
                    c.append("\t%s\t%s,%s" % (m, s, d))
    for m in ["moveq", "moveq.l"]:
        for i in ["#0", "#1", "#-1", "#127", "#-128", "#200"]:
            c.append("\t%s\t%s,d5" % (m, i))
    write(name + "_imm", args, c)

