def ok(line, args):
    with tempfile.TemporaryDirectory() as d:
        open(os.path.join(d, "t.s"), "w").write(line + "\n")
        p = subprocess.run([VASM, "-quiet", "-Fhunk", "-o", os.path.join(d, "o")] + args + ["t.s"],
                           cwd=d, capture_output=True)
        return p.returncode == 0

def write(name, args, cands, prologue=""):
    with ThreadPoolExecutor(16) as ex:
        res = list(ex.map(lambda c: ok(prologue + c, args), cands))
    good = [c for c, r in zip(cands, res) if r]
    with open(os.path.join(OUT, name + ".s"), "w") as f:
        f.write("; gfasm-args: -Fhunk %s\n" % " ".join(args))
        f.write("; generated by tests/gen/gen_insn.py (oracle-filtered)\n")
        if prologue:
            f.write(prologue)
        f.write("; --\n")
        for c in good:
            f.write(c + "\n")
    print(name, len(good), "of", len(cands))

def sized(mn, sizes):
    return [mn + ("." + s if s else "") for s in sizes]

