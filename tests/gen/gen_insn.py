def gen_branch(name, args):
    c = []
    for b in ["bra", "bsr", "bhi", "bls", "bcc", "bcs", "bne", "beq", "bvc", "bvs", "bpl",
              "bmi", "bge", "blt", "bgt", "ble", "bhs", "blo"]:
        for s in ["", ".s", ".b", ".w", ".l"]:
            for t in ["*+2", "*+4", "*+100", "*-100", "*+$1000", "*+$10000", "*-$20000", "*"]:
                c.append("\t%s%s\t%s" % (b, s, t))
    for d in ["dbra", "dbf", "dbt", "dbeq", "dbne", "dbhi", "dble"]:
        for t in ["*", "*+100", "*-$1000"]:
            c.append("\t%s\td1,%s" % (d, t))
    for j in ["jmp", "jsr"]:
        for t in ["*+10", "*+$10000", "*", "4(pc)", "(a0)", "$1234.w", "$12345678", "(*+8,pc)"]:
            c.append("\t%s\t%s" % (j, t))
    write(name + "_branch", args, c)

