#!/usr/bin/env python3
"""Generate Z80 coverage sources (oracle-filtered), like gen_ppc.py.

usage: gen_z80.py VASMZ80_OLDSTYLE outdir
"""
import os, subprocess, sys, tempfile
from concurrent.futures import ThreadPoolExecutor

VASM, OUT = sys.argv[1], sys.argv[2]
R8 = ["a", "b", "c", "d", "e", "h", "l", "(hl)", "(ix+5)", "(iy-3)", "(ix)", "(iy+127)", "(ix-128)",
      "ixh", "ixl", "iyh", "iyl", "i", "r"]
R16 = ["bc", "de", "hl", "sp", "af", "ix", "iy", "af'"]
MEM = ["(bc)", "(de)", "(sp)", "(c)", "($1234)", "($12)", "(label)", "(1+2)"]
IMM = ["0", "$12", "255", "256", "-1", "-128", "$1234", "'A'", "%101", "@11", "&ff", "12h", "0x10",
       "label", "<$1234", ">$1234"]
CC = ["nz", "z", "nc", "c", "po", "pe", "p", "m"]
JT = ["$", "$+2", "$+129", "$-126", "$+130", "$-127", "$1234", "label"]

cands = []
def emit(m, ops):
    cands.append(" %s %s" % (m, ops) if ops else " " + m)

for m in ["ld"]:
    for a in R8 + R16 + MEM:
        for b in R8 + R16 + MEM + IMM[:9]:
            emit(m, a + "," + b)
for m in "add adc sub sbc and xor or cp".split():
    for a in R8 + IMM:
        emit(m, a); emit(m, "a," + a)
    for a in ["hl", "ix", "iy"]:
        for b in R16:
            emit(m, a + "," + b)
for m in ["inc", "dec"]:
    for a in R8 + R16:
        emit(m, a)
for m in "rlc rrc rl rr sla sra sll srl".split():
    for a in R8:
        emit(m, a)
for m in "bit res set".split():
    for n in ["0", "7", "3", "8", "-1"]:
        for a in R8:
            emit(m, n + "," + a)
for m in ["push", "pop"]:
    for a in R16:
        emit(m, a)
for a in ["af,af'", "de,hl", "hl,de", "(sp),hl", "(sp),ix", "(sp),iy", "af,af"]:
    emit("ex", a)
for m in ["jp", "call"]:
    for t in JT + ["(hl)", "(ix)", "(iy)"]:
        emit(m, t)
        for c in CC:
            emit(m, c + "," + t)
for m in ["jr", "djnz"]:
    for t in JT:
        emit(m, t)
        for c in CC:
            emit(m, c + "," + t)
for c in [""] + CC:
    emit("ret", c)
for n in ["0", "8", "$10", "$18", "$20", "$28", "$30", "$38", "7", "$40", "1"]:
    emit("rst", n)
for n in ["0", "1", "2", "3"]:
    emit("im", n)
for a in ["a,($10)", "b,(c)", "a,(c)", "(c)", "f,(c)", "h,(c)", "a,(255)", "l,($fe)"]:
    emit("in", a)
for a in ["($10),a", "(c),a", "(c),b", "(c),0", "(c),l", "($ff),a", "(c),h"]:
    emit("out", a)
for m in """nop halt di ei rlca rla rrca rra daa cpl scf ccf exx neg reti retn rld rrd ldi ldir ldd lddr
cpi cpir cpd cpdr ini inir ind indr outi otir outd otdr""".split():
    emit(m, "")

def ok(line):
    with tempfile.TemporaryDirectory() as d:
        open(os.path.join(d, "t.s"), "w").write("label equ $4321\n" + line + "\n")
        p = subprocess.run([VASM, "-quiet", "-Fbin", "-o", os.path.join(d, "o"), "t.s"],
                           cwd=d, capture_output=True)
        return p.returncode == 0 and not p.stderr.strip()

with ThreadPoolExecutor(16) as ex:
    res = list(ex.map(ok, cands))
good = [c for c, r in zip(cands, res) if r]
os.makedirs(OUT, exist_ok=True)
for i in range(0, len(good), 2000):
    with open(os.path.join(OUT, "z80_insn%d.s" % (i // 2000)), "w") as f:
        f.write("; gfasm-args: -Fbin\n; gfasm-cpu: z80 oldstyle\n; generated by tests/gen/gen_z80.py (oracle-filtered)\nlabel equ $4321\n; --\n")
        for c in good[i:i + 2000]:
            f.write(c + "\n")
print(len(good), "of", len(cands))
